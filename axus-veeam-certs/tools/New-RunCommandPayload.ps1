#Requires -Version 5.1
<#
.SYNOPSIS
  Workstation helper. az vm run-command accepts ONE script, so this builds a single
  self-contained payload that (a) unpacks the project scripts to a temp folder on the server,
  (b) runs one command with the arguments given here, (c) deletes the temp folder.
  Payloads contain only the scripts in /scripts and the arguments you pass; no secrets.

.EXAMPLE  Setup payload for VSPC:
  .\tools\New-RunCommandPayload.ps1 -Name vspc-setup -Command Initialize -Arguments @{
      Role='VSPC'; Domain='vspc.axusbackups.com' }
.EXAMPLE  Staging pass on VCC (uses the installed bin copy, runs under pwsh 7):
  .\tools\New-RunCommandPayload.ps1 -Name vcc-staging -Command VccRenewal -Arguments @{ Environment='Staging'; NewOrder=$true }
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Name,
    [Parameter(Mandatory)][ValidateSet('Initialize', 'VspcRenewal', 'VccRenewal', 'RegisterTask', 'Inventory')][string]$Command,
    [hashtable]$Arguments = @{},
    [string]$OutDir = (Join-Path $PSScriptRoot '..\payloads')
)
$ErrorActionPreference = 'Stop'
$scripts = Resolve-Path (Join-Path $PSScriptRoot '..\scripts')
$bundle = 'AxusCertRenewal.psm1', 'Invoke-VccRenewal.ps1', 'Invoke-VspcRenewal.ps1', 'Register-CertRenewalTask.ps1', 'Initialize-CertRenewal.ps1', 'Get-CertInventory.ps1'

function ConvertTo-ArgLiteral($v) {
    if ($v -is [bool] -or $v -is [switch]) { if ($v) { '$true' } else { '$false' } }
    elseif ($v -is [array]) { '@(' + (($v | ForEach-Object { ConvertTo-ArgLiteral $_ }) -join ',') + ')' }
    elseif ($v -is [int]) { "$v" }
    else { "'" + ("$v" -replace "'", "''") + "'" }
}
$argLines = ($Arguments.GetEnumerator() | Sort-Object Key | ForEach-Object { "    '{0}' = {1}" -f $_.Key, (ConvertTo-ArgLiteral $_.Value) }) -join "`r`n"

$entry = @{
    Initialize   = @{ File = 'Initialize-CertRenewal.ps1'; Pwsh = $false; FromBin = $false }
    VspcRenewal  = @{ File = 'Invoke-VspcRenewal.ps1'; Pwsh = $false; FromBin = $true }
    VccRenewal   = @{ File = 'Invoke-VccRenewal.ps1'; Pwsh = $true; FromBin = $true }
    RegisterTask = @{ File = 'Register-CertRenewalTask.ps1'; Pwsh = $false; FromBin = $true }
    Inventory    = @{ File = 'Get-CertInventory.ps1'; Pwsh = $false; FromBin = $false }
}[$Command]

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# Generated by tools/New-RunCommandPayload.ps1 on $(Get-Date -Format s) - command: $Command")
[void]$sb.AppendLine('$ErrorActionPreference = ''Stop''')
[void]$sb.AppendLine('$__args = @{')
[void]$sb.AppendLine($argLines)
[void]$sb.AppendLine('}')
if ($entry.FromBin) {
    [void]$sb.AppendLine("`$__script = 'C:\ProgramData\Axus\CertRenewal\bin\$($entry.File)'")
    [void]$sb.AppendLine('if (-not (Test-Path $__script)) { throw "Not installed: $__script. Run the setup payload first." }')
    [void]$sb.AppendLine('$__stage = $null')
} else {
    [void]$sb.AppendLine('$__stage = Join-Path $env:TEMP (''axuscr-'' + [guid]::NewGuid().ToString(''N''))')
    [void]$sb.AppendLine('New-Item -ItemType Directory -Path $__stage | Out-Null')
    foreach ($f in $bundle) {
        $b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $scripts $f)))
        [void]$sb.AppendLine("[IO.File]::WriteAllBytes((Join-Path `$__stage '$f'), [Convert]::FromBase64String('$b64'))")
    }
    [void]$sb.AppendLine("`$__script = Join-Path `$__stage '$($entry.File)'")
    if ($Command -eq 'Initialize') { [void]$sb.AppendLine('$__args[''SourceDir''] = $__stage') }
}
[void]$sb.AppendLine('try {')
if ($entry.Pwsh) {
    # Pass args to pwsh as -Name value pairs; switches as -Name (true) or omitted (false).
    [void]$sb.AppendLine('    $pw = Join-Path $env:ProgramFiles ''PowerShell\7\pwsh.exe''')
    [void]$sb.AppendLine('    $a = @(''-NoProfile'', ''-NonInteractive'', ''-ExecutionPolicy'', ''Bypass'', ''-File'', $__script)')
    [void]$sb.AppendLine('    foreach ($k in $__args.Keys) { $v = $__args[$k]; if ($v -is [bool]) { if ($v) { $a += "-$k" } } else { $a += "-$k"; $a += "$v" } }')
    [void]$sb.AppendLine('    & $pw @a 2>&1 | ForEach-Object { "$_" }')
    [void]$sb.AppendLine('    "EXIT: $LASTEXITCODE"')
} else {
    [void]$sb.AppendLine('    $__sw = @{}; foreach ($k in @($__args.Keys)) { if ($__args[$k] -is [bool]) { $__sw[$k] = [switch]$__args[$k] } else { $__sw[$k] = $__args[$k] } }')
    [void]$sb.AppendLine('    & $__script @__sw 2>&1 | ForEach-Object { "$_" }')
    [void]$sb.AppendLine('    "EXIT: $LASTEXITCODE"')
}
[void]$sb.AppendLine('} finally { if ($__stage) { Remove-Item $__stage -Recurse -Force -ErrorAction SilentlyContinue } }')

if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }
$path = Join-Path (Resolve-Path $OutDir) "$Name.ps1"
[IO.File]::WriteAllText($path, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
$path
